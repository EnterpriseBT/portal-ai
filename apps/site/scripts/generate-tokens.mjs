/**
 * Theme → CSS custom properties bridge (#311).
 *
 * The app renders its themes through MUI at runtime. The marketing site
 * ships static HTML with no React and no JS requirement, so it cannot
 * consume a MUI theme object — but it must not drift from one either, or
 * the public site and the product it advertises stop looking related.
 *
 * This script is the seam: it reads the SAME two theme JSONs
 * (`@portalai/core` `assets/themes`) the app consumes and emits plain CSS
 * custom properties under `:root[data-theme="light"]` / `[data-theme="dark"]`.
 * A palette change in core reaches the site on its next build, with no
 * second copy of the colors to keep in sync.
 *
 * Output (`src/styles/tokens.css`) is generated and gitignored — it is a
 * build artifact, not source. Runs before `astro dev` and `astro build`.
 */

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require_ = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

/** Resolve core's theme dir through node resolution, not a relative guess. */
function themesDir() {
  const corePkg = require_.resolve("@portalai/core/package.json");
  return path.join(path.dirname(corePkg), "src/assets/themes");
}

const THEME_FILES = {
  light: "brand-theme.json",
  dark: "brand-theme-dark.json",
};

/** camelCase / dotted path → kebab-case token segment. */
const kebab = (s) =>
  String(s)
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();

/**
 * Flatten a theme's palette into `--color-*` declarations.
 * `primary.main` → `--color-primary-main`; a string leaf like `divider`
 * → `--color-divider`.
 */
function paletteTokens(palette) {
  const out = [];
  for (const [group, value] of Object.entries(palette ?? {})) {
    if (group === "mode") continue;
    if (typeof value === "string") {
      out.push([`--color-${kebab(group)}`, value]);
      continue;
    }
    for (const [leaf, leafValue] of Object.entries(value ?? {})) {
      if (typeof leafValue !== "string" && typeof leafValue !== "number") {
        continue;
      }
      out.push([`--color-${kebab(group)}-${kebab(leaf)}`, String(leafValue)]);
    }
  }
  return out;
}

/** Font families, the base size, and the weight scale. */
function typographyTokens(typography) {
  const out = [];
  const t = typography ?? {};
  if (t.fontFamily) out.push(["--font-family-body", t.fontFamily]);
  if (t.h1?.fontFamily) out.push(["--font-family-heading", t.h1.fontFamily]);
  if (t.monospace?.fontFamily || t.code?.fontFamily) {
    out.push([
      "--font-family-mono",
      t.monospace?.fontFamily ?? t.code.fontFamily,
    ]);
  }
  if (t.fontSize) out.push(["--font-size-base", `${t.fontSize}px`]);
  for (const weight of ["Light", "Regular", "Medium", "Bold"]) {
    const value = t[`fontWeight${weight}`];
    if (value) out.push([`--font-weight-${weight.toLowerCase()}`, String(value)]);
  }
  // Heading scale — the site's own type ramp reads from these.
  for (const level of ["h1", "h2", "h3", "h4", "h5", "h6"]) {
    if (t[level]?.fontSize) {
      out.push([`--font-size-${level}`, String(t[level].fontSize)]);
    }
  }
  return out;
}

/** Spacing unit, radius, and breakpoints — identical across both themes,
 *  but emitted per-theme so a future divergence needs no script change. */
function layoutTokens(theme) {
  const out = [];
  if (theme.spacing != null) {
    out.push(["--space-unit", `${theme.spacing}px`]);
  }
  if (theme.shape?.borderRadius != null) {
    out.push(["--radius-base", `${theme.shape.borderRadius}px`]);
  }
  for (const [name, value] of Object.entries(
    theme.breakpoints?.values ?? {}
  )) {
    out.push([`--bp-${kebab(name)}`, `${value}px`]);
  }
  return out;
}

function blockFor(themeName, theme) {
  const tokens = [
    ...paletteTokens(theme.palette),
    ...typographyTokens(theme.typography),
    ...layoutTokens(theme),
  ];
  const body = tokens
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `:root[data-theme="${themeName}"] {\n${body}\n}`;
}

export function generateTokensCss(themes) {
  return [
    "/* GENERATED by scripts/generate-tokens.mjs — do not edit.",
    " * Source: @portalai/core assets/themes/*.json (#311).",
    " * Regenerate with `npm run build:tokens`.",
    " */",
    "",
    blockFor("light", themes.light),
    "",
    blockFor("dark", themes.dark),
    "",
  ].join("\n");
}

export function readThemes(dir = themesDir()) {
  const read = (file) =>
    JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
  return { light: read(THEME_FILES.light), dark: read(THEME_FILES.dark) };
}

/** Written only when invoked directly, so the module stays importable
 *  from tests without side effects. */
const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const outPath = path.join(here, "../src/styles/tokens.css");
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  const css = generateTokensCss(readThemes());
  fs.writeFileSync(outPath, css);
  const count = (css.match(/^\s+--/gm) ?? []).length;
  console.log(`generate-tokens — ${count} custom properties → ${outPath}`);
}
